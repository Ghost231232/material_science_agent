_TERM_INDEX = None


def _index() -> list[tuple[str, str, dict]]:
    global _TERM_INDEX
    if _TERM_INDEX is None:
        _TERM_INDEX = []
        for e in GLOSSARY:
            for a in [e["term"], *e["aliases"]]:
                _TERM_INDEX.append((a, e["term"], e))
        _TERM_INDEX.sort(key=lambda x: -len(x[0]))  # 长词优先
    return _TERM_INDEX


def terms_preview(n: int = 12) -> str:
    names = [e["term"] for e in GLOSSARY]
    return "、".join(names[:n]) + (f" 等共 {len(names)} 个术语。" if len(names) > n else "。")


def answer(text: str) -> str | None:
    """识别术语并返回解释；未命中术语时返回 None（交由其他意图处理）。"""
    for alias, term, e in _index():
        if alias in text:
            related = [t for t in (m["term"] for m in GLOSSARY) if t != term
                       and any(w in e["text"] for w in (t,))]
            extra = f"\n相关术语：{'、'.join(related[:3])}" if related else ""
            return f"【{term}】\n{e['text']}{extra}"
    # 明确在问概念但未命中
    if any(k in text for k in ["是什么", "什么是", "解释", "什么意思", "定义"]) and "材料" not in text.replace("材料科学", ""):
        return f"知识库中暂时没有这个术语。目前已收录：{terms_preview()}\n可直接说「术语列表」查看全部。"
    return None


def list_terms() -> str:
    return "已收录术语：\n" + "、".join(e["term"] for e in GLOSSARY)
